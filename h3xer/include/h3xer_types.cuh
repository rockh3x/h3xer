 * H3XER - High-Performance RAR5 Password Recovery Tool
 * Core type definitions and constants
 *
 * RAR5 uses PBKDF2-HMAC-SHA256 with 32768 iterations (not 65536!)
 * followed by AES-256-CBC for encryption verification
 */

