// ============================================================================
// RAR5 Cryptographic Constants
// ============================================================================

// RAR5 uses 2^15 = 32768 iterations for PBKDF2
constexpr uint32_t RAR5_PBKDF2_ITERATIONS = 32768;

// Salt size in bytes (always 16 for RAR5)
constexpr uint32_t RAR5_SALT_SIZE = 16;

// Derived key size (256-bit AES key)
constexpr uint32_t RAR5_KEY_SIZE = 32;

// AES block size
constexpr uint32_t AES_BLOCK_SIZE = 16;

// Check value size (encrypted check bytes for verification)
constexpr uint32_t RAR5_CHECK_SIZE = 16;

// SHA-256 constants
constexpr uint32_t SHA256_BLOCK_SIZE = 64;
constexpr uint32_t SHA256_DIGEST_SIZE = 32;

// Maximum password length we support
constexpr uint32_t MAX_PASSWORD_LEN = 128;

// Maximum mask length
constexpr uint32_t MAX_MASK_LEN = 32;

// ============================================================================
// Kernel Configuration
// ============================================================================

// Threads per block - 256 is optimal for most compute-bound kernels
constexpr uint32_t THREADS_PER_BLOCK = 256;

// Maximum passwords to process per kernel launch
constexpr uint32_t MAX_BATCH_SIZE = 1U << 20; // ~1M candidates

// ============================================================================
// Data Structures
// ============================================================================

// RAR5 archive header data needed for cracking
struct alignas(16) Rar5Header {
  uint8_t salt[RAR5_SALT_SIZE];         // PBKDF2 salt
  uint8_t check_value[RAR5_CHECK_SIZE]; // Encrypted check bytes
  uint8_t iv[AES_BLOCK_SIZE]; // AES-CBC IV (usually all zeros for check)
  uint8_t pswcheck[8];        // Password check value (optional, 8 bytes)
  uint32_t pswcheck_present;  // Whether pswcheck is present
};

// Mask attack position definition
struct MaskPosition {
  uint8_t charset[256]; // Characters in this position
  uint8_t count;        // Number of characters
};

// Result structure for found passwords
struct CrackResult {
  uint32_t found;                     // 1 if password found
  uint32_t candidate_idx;             // Index of successful candidate
  uint8_t password[MAX_PASSWORD_LEN]; // The found password
  uint32_t password_len;              // Length of found password
};

// Kernel launch parameters
struct KernelParams {
  uint64_t start_idx;      // Starting candidate index
  uint64_t num_candidates; // Number of candidates to try
  uint32_t password_len;   // Fixed password length (for mask)
};

